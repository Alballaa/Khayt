#!/usr/bin/env node
/**
 * E2E: drop a model file on the calculator and check the quote fields fill.
 *
 * The pure modules are unit-tested, but nothing else proves the CHAIN works:
 * renderer reads bytes → hub:intake-model-bytes → lib/model-intake → back →
 * lib/intake-view → the actual <input> a shop reads a price off. This drives
 * that end to end in a real Electron window.
 *
 * Requires display (use xvfb-run on Linux CI).
 */
import fs from 'fs';
import zipWrite from '../lib/zip-write.js';
import { dismissWizard, launchApp, makeUserDataDir, switchTab } from './e2e/helpers.mjs';

const userData = makeUserDataDir();
let electronApp;

const PRUSA_CFG = [
  '; generated by PrusaSlicer 2.8.0 on 2026-07-31',
  '; estimated printing time (normal mode) = 3h 12m 40s',
  '; filament used [g] = 41.83',
  '; filament_type = PLA',
].join('\n');

/** A 20mm tetrahedron — solid volume 20·20·20/6 = 1333.33 mm3. */
const TETRA = '<?xml version="1.0"?><model unit="millimeter"><resources>'
  + '<object id="1" type="model"><mesh><vertices>'
  + '<vertex x="0" y="0" z="0"/><vertex x="20" y="0" z="0"/>'
  + '<vertex x="0" y="20" z="0"/><vertex x="0" y="0" z="20"/>'
  + '</vertices><triangles>'
  + '<triangle v1="0" v2="2" v3="1"/><triangle v1="0" v2="1" v3="3"/>'
  + '<triangle v1="0" v2="3" v3="2"/><triangle v1="1" v2="2" v3="3"/>'
  + '</triangles></mesh></object></resources>'
  + '<build><item objectid="1" transform="1 0 0 0 1 0 0 0 1 0 0 0"/></build></model>';

const b64 = (buf) => Buffer.from(buf).toString('base64');

/** Drive the page's own drop handler with a real File built from bytes. */
async function dropFile(window, filename, base64) {
  return window.evaluate(async ([name, data]) => {
    const bin = atob(data);
    const bytes = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
    const file = new File([bytes], name);
    const dt = new DataTransfer();
    dt.items.add(file);
    const zone = document.querySelector('#modelDrop');
    if (!zone) throw new Error('#modelDrop is not in the DOM');
    zone.dispatchEvent(new DragEvent('drop', { dataTransfer: dt, bubbles: true, cancelable: true }));
    return true;
  }, [filename, base64]);
}

const readForm = (window) => window.evaluate(() => ({
  weight: document.querySelector('#printWeight')?.value,
  time: document.querySelector('#printTime')?.value,
  note: document.querySelector('#stlEstimateNote')?.textContent || '',
  noteShown: document.querySelector('#stlEstimateNote')?.style.display !== 'none',
}));

async function clearForm(window) {
  await window.evaluate(() => {
    for (const id of ['#printWeight', '#printTime']) {
      const el = document.querySelector(id);
      if (el) { el.value = ''; }
    }
    const n = document.querySelector('#stlEstimateNote');
    if (n) { n.textContent = ''; n.style.display = 'none'; }
  });
}

async function testSlicedFillsExactNumbers(window) {
  const buf = zipWrite.writeZip([
    { name: '3D/3dmodel.model', data: Buffer.from(TETRA, 'utf8') },
    { name: 'Metadata/Slic3r_PE.config', data: Buffer.from(PRUSA_CFG, 'utf8') },
  ]);
  await clearForm(window);
  await dropFile(window, 'sliced.3mf', b64(buf));
  await window.waitForFunction(() => document.querySelector('#printWeight')?.value !== '');
  const f = await readForm(window);

  // 41.83 g and 3h 12m 40s = 193 min = 3.22 h — the slicer's own figures.
  if (Number(f.weight) !== 41.8) throw new Error(`weight was ${f.weight}, expected 41.8`);
  if (Number(f.time) !== 3.22) throw new Error(`time was ${f.time}, expected 3.22`);
  if (!f.noteShown) throw new Error('the provenance note was not shown');
  if (!/PrusaSlicer/.test(f.note)) throw new Error(`note does not name the slicer: ${f.note}`);
  // Match the estimate CAVEAT, not the word "estimate" — the exact wording ends
  // "…not an estimate", so a bare word match would flag the correct message.
  if (/never sliced/i.test(f.note)) {
    throw new Error(`a sliced result must NOT carry the estimate caveat: ${f.note}`);
  }
  if (!/not an estimate/i.test(f.note)) {
    throw new Error(`a sliced result should say so plainly: ${f.note}`);
  }
}

async function testUnslicedIsLabelledAnEstimate(window) {
  const buf = zipWrite.writeZip([{ name: '3D/3dmodel.model', data: Buffer.from(TETRA, 'utf8') }]);
  await clearForm(window);
  await dropFile(window, 'raw.3mf', b64(buf));
  await window.waitForFunction(() => document.querySelector('#printWeight')?.value !== '');
  const f = await readForm(window);

  if (!(Number(f.weight) > 0)) throw new Error(`no weight was estimated (${f.weight})`);
  if (!f.noteShown) throw new Error('the estimate note was not shown');
  // The whole point: this number must be visibly flagged as an assumption.
  if (!/never sliced/i.test(f.note)) {
    throw new Error(`an unsliced model must carry the estimate caveat: ${f.note}`);
  }
  if (!/20/.test(f.note)) throw new Error(`note omits the measured dimensions: ${f.note}`);
}

async function testObjIsAccepted(window) {
  // The format R1 added. A 20mm cube: 8000 mm3 solid.
  const cube = ['v 0 0 0', 'v 20 0 0', 'v 20 20 0', 'v 0 20 0',
    'v 0 0 20', 'v 20 0 20', 'v 20 20 20', 'v 0 20 20',
    'f 1 4 3', 'f 1 3 2', 'f 5 6 7', 'f 5 7 8', 'f 1 2 6', 'f 1 6 5',
    'f 2 3 7', 'f 2 7 6', 'f 3 4 8', 'f 3 8 7', 'f 4 1 5', 'f 4 5 8'].join('\n');
  await clearForm(window);
  await dropFile(window, 'cube.obj', b64(Buffer.from(cube, 'utf8')));
  await window.waitForFunction(() => document.querySelector('#printWeight')?.value !== '');
  const f = await readForm(window);
  if (!(Number(f.weight) > 0)) throw new Error(`OBJ produced no weight (${f.weight})`);
  if (!/never sliced/i.test(f.note)) throw new Error(`OBJ must carry the estimate caveat: ${f.note}`);
}

async function testGcodeHeadTailSlicing(window) {
  // A large G-code must still be read: the renderer sends only head+tail, and
  // the summary lives in the footer. Pad past the 192 KB cutoff.
  const padding = 'G1 X1 Y1 E0.1\n'.repeat(20000);          // ~280 KB
  const gcode = '; generated by PrusaSlicer 2.8.0\n' + padding + PRUSA_CFG;
  await clearForm(window);
  await dropFile(window, 'big.gcode', b64(Buffer.from(gcode, 'utf8')));
  await window.waitForFunction(() => document.querySelector('#printWeight')?.value !== '');
  const f = await readForm(window);
  if (Number(f.weight) !== 41.8) {
    throw new Error(`footer summary was lost in the head+tail read (weight ${f.weight})`);
  }
}

try {
  ({ electronApp } = await launchApp(userData));
  const window = await electronApp.firstWindow();
  window.setDefaultTimeout(120_000);
  await dismissWizard(window);
  await switchTab(window, 'calculator-tab');
  await window.waitForSelector('#modelDrop');

  await testSlicedFillsExactNumbers(window);
  await testUnslicedIsLabelledAnEstimate(window);
  await testObjIsAccepted(window);
  await testGcodeHeadTailSlicing(window);

  console.log('e2e-model-intake: ok (sliced 3MF exact, unsliced labelled, OBJ, big G-code)');
} finally {
  if (electronApp) await electronApp.close().catch(() => {});
  fs.rmSync(userData, { recursive: true, force: true });
}
