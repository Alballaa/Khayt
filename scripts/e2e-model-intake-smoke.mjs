#!/usr/bin/env node
/**
 * E2E: drop a model file on the calculator and check the quote fields fill.
 *
 * The pure modules are unit-tested, but nothing else proves the CHAIN works:
 * renderer reads bytes → hub:intake-model-bytes → lib/model-intake → back →
 * lib/intake-view → the actual <input> a shop reads a price off. This drives
 * that end to end in a real Electron window.
 *
 * Requires display (use xvfb-run on Linux CI).
 */
import fs from 'fs';
import zipWrite from '../lib/zip-write.js';
import { dismissWizard, launchApp, makeUserDataDir, switchTab } from './e2e/helpers.mjs';

const userData = makeUserDataDir();
let electronApp;

const PRUSA_CFG = [
  '; generated by PrusaSlicer 2.8.0 on 2026-07-31',
  '; estimated printing time (normal mode) = 3h 12m 40s',
  '; filament used [g] = 41.83',
  '; filament_type = PLA',
].join('\n');

/** A 20mm tetrahedron — solid volume 20·20·20/6 = 1333.33 mm3. */
const TETRA = '<?xml version="1.0"?><model unit="millimeter"><resources>'
  + '<object id="1" type="model"><mesh><vertices>'
  + '<vertex x="0" y="0" z="0"/><vertex x="20" y="0" z="0"/>'
  + '<vertex x="0" y="20" z="0"/><vertex x="0" y="0" z="20"/>'
  + '</vertices><triangles>'
  + '<triangle v1="0" v2="2" v3="1"/><triangle v1="0" v2="1" v3="3"/>'
  + '<triangle v1="0" v2="3" v3="2"/><triangle v1="1" v2="2" v3="3"/>'
  + '</triangles></mesh></object></resources>'
  + '<build><item objectid="1" transform="1 0 0 0 1 0 0 0 1 0 0 0"/></build></model>';

const b64 = (buf) => Buffer.from(buf).toString('base64');

/** Drive the page's own drop handler with a real File built from bytes. */
async function dropFile(window, filename, base64) {
  return window.evaluate(async ([name, data]) => {
    const bin = atob(data);
    const bytes = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
    const file = new File([bytes], name);
    const dt = new DataTransfer();
    dt.items.add(file);
    const zone = document.querySelector('#modelDrop');
    if (!zone) throw new Error('#modelDrop is not in the DOM');
    zone.dispatchEvent(new DragEvent('drop', { dataTransfer: dt, bubbles: true, cancelable: true }));
    return true;
  }, [filename, base64]);
}

const readForm = (window) => window.evaluate(() => ({
  weight: document.querySelector('#printWeight')?.value,
  time: document.querySelector('#printTime')?.value,
  note: document.querySelector('#stlEstimateNote')?.textContent || '',
  noteShown: document.querySelector('#stlEstimateNote')?.style.display !== 'none',
}));

async function clearForm(window) {
  await window.evaluate(() => {
    for (const id of ['#printWeight', '#printTime']) {
      const el = document.querySelector(id);
      if (el) { el.value = ''; }
    }
    const n = document.querySelector('#stlEstimateNote');
    if (n) { n.textContent = ''; n.style.display = 'none'; }
  });
}

async function testSlicedFillsExactNumbers(window) {
  const buf = zipWrite.writeZip([
    { name: '3D/3dmodel.model', data: Buffer.from(TETRA, 'utf8') },
    { name: 'Metadata/Slic3r_PE.config', data: Buffer.from(PRUSA_CFG, 'utf8') },
  ]);
  await clearForm(window);
  await dropFile(window, 'sliced.3mf', b64(buf));
  await window.waitForFunction(() => document.querySelector('#printWeight')?.value !== '');
  const f = await readForm(window);

  // 41.83 g and 3h 12m 40s = 193 min = 3.22 h — the slicer's own figures.
  if (Number(f.weight) !== 41.8) throw new Error(`weight was ${f.weight}, expected 41.8`);
  if (Number(f.time) !== 3.22) throw new Error(`time was ${f.time}, expected 3.22`);
  if (!f.noteShown) throw new Error('the provenance note was not shown');
  if (!/PrusaSlicer/.test(f.note)) throw new Error(`note does not name the slicer: ${f.note}`);
  // Match the estimate CAVEAT, not the word "estimate" — the exact wording ends
  // "…not an estimate", so a bare word match would flag the correct message.
  if (/never sliced/i.test(f.note)) {
    throw new Error(`a sliced result must NOT carry the estimate caveat: ${f.note}`);
  }
  if (!/not an estimate/i.test(f.note)) {
    throw new Error(`a sliced result should say so plainly: ${f.note}`);
  }
}

async function testUnslicedIsLabelledAnEstimate(window) {
  const buf = zipWrite.writeZip([{ name: '3D/3dmodel.model', data: Buffer.from(TETRA, 'utf8') }]);
  await clearForm(window);
  await dropFile(window, 'raw.3mf', b64(buf));
  await window.waitForFunction(() => document.querySelector('#printWeight')?.value !== '');
  const f = await readForm(window);

  if (!(Number(f.weight) > 0)) throw new Error(`no weight was estimated (${f.weight})`);
  if (!f.noteShown) throw new Error('the estimate note was not shown');
  // The whole point: this number must be visibly flagged as an assumption.
  if (!/never sliced/i.test(f.note)) {
    throw new Error(`an unsliced model must carry the estimate caveat: ${f.note}`);
  }
  if (!/20/.test(f.note)) throw new Error(`note omits the measured dimensions: ${f.note}`);
}

async function testObjIsAccepted(window) {
  // The format R1 added. A 20mm cube: 8000 mm3 solid.
  const cube = ['v 0 0 0', 'v 20 0 0', 'v 20 20 0', 'v 0 20 0',
    'v 0 0 20', 'v 20 0 20', 'v 20 20 20', 'v 0 20 20',
    'f 1 4 3', 'f 1 3 2', 'f 5 6 7', 'f 5 7 8', 'f 1 2 6', 'f 1 6 5',
    'f 2 3 7', 'f 2 7 6', 'f 3 4 8', 'f 3 8 7', 'f 4 1 5', 'f 4 5 8'].join('\n');
  await clearForm(window);
  await dropFile(window, 'cube.obj', b64(Buffer.from(cube, 'utf8')));
  await window.waitForFunction(() => document.querySelector('#printWeight')?.value !== '');
  const f = await readForm(window);
  if (!(Number(f.weight) > 0)) throw new Error(`OBJ produced no weight (${f.weight})`);
  if (!/never sliced/i.test(f.note)) throw new Error(`OBJ must carry the estimate caveat: ${f.note}`);
}

async function testGcodeHeadTailSlicing(window) {
  // A large G-code must still be read: the renderer sends only head+tail, and
  // the summary lives in the footer. Pad past the 192 KB cutoff.
  const padding = 'G1 X1 Y1 E0.1\n'.repeat(20000);          // ~280 KB
  const gcode = '; generated by PrusaSlicer 2.8.0\n' + padding + PRUSA_CFG;
  await clearForm(window);
  await dropFile(window, 'big.gcode', b64(Buffer.from(gcode, 'utf8')));
  await window.waitForFunction(() => document.querySelector('#printWeight')?.value !== '');
  const f = await readForm(window);
  if (Number(f.weight) !== 41.8) {
    throw new Error(`footer summary was lost in the head+tail read (weight ${f.weight})`);
  }
}

const rawTetra = () => zipWrite.writeZip([{ name: '3D/3dmodel.model', data: Buffer.from(TETRA, 'utf8') }]);

/** Configure the estimator the way a shop does — through the panel. */
async function setShopEstimator(window, { density, wall, infill }) {
  await switchTab(window, 'settings-tab');
  await window.click('.settings-nav-item[data-settings-section="prefs"]');
  await window.waitForSelector('#est_density');
  await window.evaluate(({ d, w, i }) => {
    const el = document.querySelector('#estimatorSettings');
    const set = (sel, v) => {
      const f = el.querySelector(sel);
      f.value = String(v); f.dispatchEvent(new Event('change', { bubbles: true }));
    };
    set('#est_density', d);
    set('#est_wall', w);
    if (i != null) set('#est_infill', i);
  }, { d: density, w: wall, i: infill });
  await switchTab(window, 'calculator-tab');
  await window.waitForSelector('#modelDrop');
}

/** Clear the per-part infill box, so the shop's configured default applies. */
const clearPartInfill = (window) => window.evaluate(() => {
  const i = document.querySelector('#infill');
  if (i) i.value = '';
});

/** Type an infill the way a shop does, and let the change reach the wiring. */
async function typeInfill(window, pct) {
  await window.evaluate((v) => {
    const i = document.querySelector('#infill');
    i.value = String(v);
    i.dispatchEvent(new Event('input', { bubbles: true }));
    i.dispatchEvent(new Event('change', { bubbles: true }));
  }, pct);
  await window.waitForTimeout(400);
}

async function selectPrinter(window, id) {
  await window.evaluate((v) => {
    const s = document.querySelector('#partMachineId');
    s.value = v;
    s.dispatchEvent(new Event('change', { bubbles: true }));
  }, id);
  await window.waitForTimeout(400);
}

async function dropRaw(window) {
  await clearForm(window);
  await dropFile(window, 'raw.3mf', b64(rawTetra()));
  await window.waitForFunction(() => document.querySelector('#printWeight')?.value !== '');
  return readForm(window);
}

/**
 * The shop's own settings must reach the file it just dropped.
 *
 * They did not. presentIntake forwarded the infill and dropped everything else,
 * so the note quoted PLA at 1.24 g/cm³ to a shop that had configured something
 * different two tabs away — and the price came from the same wrong number.
 */
async function testShopSettingsReachTheDroppedFile(window) {
  await setShopEstimator(window, { density: 4.0, wall: 1.2 });
  const f = await dropRaw(window);
  if (/1\.24/.test(f.note)) {
    throw new Error(`the note still quotes the default PLA density: ${f.note}`);
  }
  if (!/·\s*4\s*g\/cm³/.test(f.note)) {
    throw new Error(`the shop's density never reached the note: ${f.note}`);
  }
}

/**
 * And so must a rate learned from the shop's own finished jobs — visibly.
 *
 * A measured number and an assumed one must never present identically, so this
 * asserts the wording changes as well as the figure.
 */
async function testMeasuredRateReachesTheDroppedFile(window) {
  await setShopEstimator(window, { density: 1.27, wall: 1.2 });   // PETG
  const before = await dropRaw(window);
  if (!/assum/i.test(before.note)) {
    throw new Error(`with no history the note must admit it is guessing: ${before.note}`);
  }

  // Four finished jobs a printer reported itself — about 12 g/h, not the ~35
  // the shipped throughput implies.
  await window.evaluate(() => {
    const measured = { time: 'moonraker', weight: 'moonraker' };
    const job = (h, g) => ({
      id: 'CAL-' + h, machineId: 'M1',
      actualPrintTime: h, actualWeight: g, actualsSource: measured,
      parts: [{ id: 'p', printFileId: 'F1', setupId: 'S1', printTime: h, printWeight: g, qty: 1 }],
    });
    printLog.unshift(job(3, 36), job(4, 49), job(2, 23), job(5, 62));
    saveAll();
  });

  const after = await dropRaw(window);
  if (after.time === before.time) {
    throw new Error(`the measured rate never reached the calculator — time stayed ${after.time} h`);
  }
  if (!(Number(after.time) > Number(before.time))) {
    throw new Error(`a slower measured rate must mean a longer job: ${after.time} vs ${before.time}`);
  }
  if (Number(after.weight) !== Number(before.weight)) {
    throw new Error(`only the time was ever guessed, but the weight moved: ${after.weight} vs ${before.weight}`);
  }
  if (!/measured/i.test(after.note)) {
    throw new Error(`the note does not say the rate was measured: ${after.note}`);
  }
  if (!/12(\.\d)?\s*g\/h/.test(after.note)) {
    throw new Error(`the measured rate itself is not shown: ${after.note}`);
  }
  if (!/4 finished jobs/i.test(after.note)) {
    throw new Error(`the note does not say how many jobs earned it: ${after.note}`);
  }
  // No printer is selected on the part, so this rate is pooled across the shop
  // — it must not claim to describe one machine.
  if (!/across your printers/i.test(after.note)) {
    throw new Error(`a shop-wide rate should say so: ${after.note}`);
  }
  // And it must not read as a machine specification. Grams-per-hour follows the
  // part, not the printer: on the shop's own U1 it measured anywhere from 1.9 to
  // 48.6 g/h across 67 jobs. The median is the right number; stated bare it
  // invites a shop to plan as though the next job will hit it.
  if (!/give or take \d+%/.test(after.note)) {
    throw new Error(`the note states a rate without its spread: ${after.note}`);
  }
}

/**
 * Selecting the printer changes WHOSE history the rate came from, and says so.
 *
 * calibrate() prefers a machine's own jobs and falls back to the shop pool, so
 * the same four jobs describe "this printer" once the part is assigned to it and
 * "your printers" when it is not. The claim is genuinely different and the note
 * must not present the weaker one as the stronger.
 */
async function testScopeFollowsTheSelectedPrinter(window) {
  const pooled = await dropRaw(window);            // still nothing selected

  await window.evaluate(() => {
    // The four seeded jobs all ran on M1.
    if (!Array.isArray(window.machines)) window.machines = [];
    if (!machines.some((m) => m.id === 'M1')) machines.push({ id: 'M1', name: 'E2E Printer' });
    renderMachineDropdown();
    const sel = document.querySelector('#partMachineId');
    if (!sel) throw new Error('#partMachineId is not in the DOM');
    sel.value = 'M1';
    if (sel.value !== 'M1') throw new Error('the printer never reached the dropdown');
    sel.dispatchEvent(new Event('change', { bubbles: true }));
  });

  const own = await dropRaw(window);
  if (!/on this printer/i.test(own.note)) {
    throw new Error(`with a printer selected the note should name it: ${own.note}`);
  }
  if (/across your printers/i.test(own.note)) {
    throw new Error(`a machine-scoped rate still claims the shop pool: ${own.note}`);
  }
  if (own.note === pooled.note) {
    throw new Error('selecting the printer changed nothing the shop can see');
  }
  // Same four jobs either way — only the provenance moved, so the figure itself
  // must not have.
  if (Number(own.time) !== Number(pooled.time)) {
    throw new Error(`the rate itself changed with the scope: ${own.time} vs ${pooled.time}`);
  }
}

/**
 * The estimator panel's "Default infill %" must reach the shop's own calculator.
 *
 * It did not. The per-part infill box starts blank, and the calculator fell back
 * to a hardcoded 20 rather than the shop's setting — so a shop configured for 60%
 * quoted every dropped file at 20% while the customer's intake form, which reads
 * the setting directly, quoted the same file at 60%.
 */
async function testShopDefaultInfillReachesTheDrop(window) {
  await clearPartInfill(window);

  await setShopEstimator(window, { density: 1.24, wall: 1.2, infill: 60 });
  const dense = await dropRaw(window);
  if (!/60% infill/.test(dense.note)) {
    throw new Error(`the shop's default infill never reached the drop: ${dense.note}`);
  }

  await clearPartInfill(window);
  await setShopEstimator(window, { density: 1.24, wall: 1.2, infill: 20 });
  const sparse = await dropRaw(window);
  if (!/20% infill/.test(sparse.note)) {
    throw new Error(`changing the shop default changed nothing: ${sparse.note}`);
  }
  if (!(Number(dense.weight) > Number(sparse.weight))) {
    throw new Error(`60% must weigh more than 20%: ${dense.weight} vs ${sparse.weight}`);
  }

  // A figure typed for THIS part still beats the shop-wide default.
  await typeInfill(window, 90);
  const typed = await readForm(window);
  if (!/90% infill/.test(typed.note)) {
    throw new Error(`a typed infill must win over the default: ${typed.note}`);
  }
}

/**
 * Changing what the estimate was built on must change the estimate.
 *
 * The numbers were computed once, at drop time, and never again — so setting 90%
 * infill afterwards left the form showing 90 beside a note insisting on 20%,
 * with the price built on the one the shop could not see.
 */
async function testChangingInfillRecomputes(window) {
  await clearPartInfill(window);
  await setShopEstimator(window, { density: 1.27, wall: 1.2, infill: 20 });
  const before = await dropRaw(window);

  await typeInfill(window, 90);
  const after = await readForm(window);
  if (!(Number(after.weight) > Number(before.weight))) {
    throw new Error(`the estimate never recomputed: ${after.weight} vs ${before.weight}`);
  }
  if (!/90% infill/.test(after.note)) {
    throw new Error(`the note still contradicts the infill field: ${after.note}`);
  }
  if (/20% infill/.test(after.note)) {
    throw new Error(`the note kept the infill it was dropped with: ${after.note}`);
  }
}

/**
 * And so must selecting the printer — dropping the file first is the natural
 * order, and a machine with its own measured rate was ignored until re-drop.
 */
async function testSelectingPrinterRecomputes(window) {
  await selectPrinter(window, '');
  const pooled = await dropRaw(window);
  if (!/across your printers/i.test(pooled.note)) {
    throw new Error(`with no printer chosen the rate is shop-wide: ${pooled.note}`);
  }

  await selectPrinter(window, 'M1');           // never re-dropped
  const own = await readForm(window);
  if (!/on this printer/i.test(own.note)) {
    throw new Error(`choosing the printer did not recompute the scope: ${own.note}`);
  }

  // A printer with no history of its own must fall back, not inherit the claim.
  await selectPrinter(window, 'M2');
  const other = await readForm(window);
  if (!/across your printers/i.test(other.note)) {
    throw new Error(`a printer with no history still claims its own rate: ${other.note}`);
  }
}

/**
 * A slicer's figures do not depend on the infill or the machine, so nothing may
 * recompute them — a shop that corrects a weight by hand and then adjusts the
 * infill must not have its correction thrown away.
 */
async function testASlicedResultIsNeverRecomputed(window) {
  await clearForm(window);
  await dropFile(window, 'sliced.3mf', b64(zipWrite.writeZip([
    { name: '3D/3dmodel.model', data: Buffer.from(TETRA, 'utf8') },
    { name: 'Metadata/Slic3r_PE.config', data: Buffer.from(PRUSA_CFG, 'utf8') },
  ])));
  await window.waitForFunction(() => document.querySelector('#printWeight')?.value !== '');

  // The shop knows this part purges badly and corrects the figure.
  await window.evaluate(() => {
    const w = document.querySelector('#printWeight');
    w.value = '55'; w.dispatchEvent(new Event('input', { bubbles: true }));
  });

  await typeInfill(window, 85);
  await selectPrinter(window, 'M1');

  const f = await readForm(window);
  if (Number(f.weight) !== 55) {
    throw new Error(`a hand-corrected slicer figure was recomputed away: ${f.weight}`);
  }
  if (/never sliced/i.test(f.note)) {
    throw new Error(`an exact result was turned into an estimate: ${f.note}`);
  }
}

/** A recompute the shop did not ask for by name must not announce itself. */
async function testRecomputeIsQuiet(window) {
  await clearPartInfill(window);
  await dropRaw(window);
  await window.evaluate(() => {
    document.querySelectorAll('#toastContainer .toast').forEach((el) => el.remove());
  });
  await typeInfill(window, 45);
  await selectPrinter(window, 'M1');
  const toasts = await window.evaluate(() =>
    [...document.querySelectorAll('#toastContainer .toast')].map((el) => el.textContent));
  if (toasts.length) {
    throw new Error(`recomputing announced itself ${toasts.length}×: ${JSON.stringify(toasts)}`);
  }
}

/**
 * Once the part is added the model is no longer in the form, so the estimate
 * must be forgotten — otherwise the next infill the shop typed pulled the
 * previous part's model back into a blank form.
 */
async function testAddingThePartForgetsTheModel(window) {
  await clearPartInfill(window);
  const est = await dropRaw(window);
  if (!(Number(est.weight) > 0)) throw new Error('nothing to add');

  await window.click('#btnAddPart');
  await window.waitForTimeout(500);

  const cleared = await readForm(window);
  if (cleared.noteShown) {
    throw new Error(`the estimate note outlived the part it described: ${cleared.note}`);
  }

  // The form is empty now; typing an infill must not resurrect the old model.
  await typeInfill(window, 70);
  const after = await readForm(window);
  if (Number(after.weight) > 0) {
    throw new Error(`a cleared form was refilled from the previous part's model: ${after.weight} g`);
  }
}

try {
  ({ electronApp } = await launchApp(userData));
  const window = await electronApp.firstWindow();
  window.setDefaultTimeout(120_000);
  await dismissWizard(window);
  await switchTab(window, 'calculator-tab');
  await window.waitForSelector('#modelDrop');

  await testSlicedFillsExactNumbers(window);
  await testUnslicedIsLabelledAnEstimate(window);
  await testObjIsAccepted(window);
  await testGcodeHeadTailSlicing(window);
  // Last: these change the shop's settings and its print history.
  await testShopSettingsReachTheDroppedFile(window);
  await testMeasuredRateReachesTheDroppedFile(window);
  await testScopeFollowsTheSelectedPrinter(window);
  await testShopDefaultInfillReachesTheDrop(window);
  await testChangingInfillRecomputes(window);
  await testSelectingPrinterRecomputes(window);
  await testASlicedResultIsNeverRecomputed(window);
  await testRecomputeIsQuiet(window);
  await testAddingThePartForgetsTheModel(window);

  console.log('e2e-model-intake: ok (sliced 3MF exact, unsliced labelled, OBJ, big G-code,'
    + ' shop settings reach the drop, measured rate reaches it, scope follows the printer,'
    + ' default infill applies, infill and printer recompute, add-part forgets the model)');
} finally {
  if (electronApp) await electronApp.close().catch(() => {});
  fs.rmSync(userData, { recursive: true, force: true });
}
