#!/usr/bin/env node
/**
 * Re-hash an electron-updater feed after something changed the artifact bytes.
 *
 * Signing and stapling happen AFTER electron-builder computed the feed hashes,
 * so `latest.yml` / `latest-mac.yml` then describe bytes that no longer exist.
 * electron-updater refuses the download with a sha512 mismatch, and the failure
 * lands on users mid-update rather than in CI — nothing about the release looks
 * wrong until someone's app declines to update.
 *
 * This has already been done by hand once per macOS release (staple the .dmg,
 * then edit the sha512 and size in latest-mac.yml). Doing it by hand is fine
 * until the day it is done wrong, and it is the exact shape of edit a machine
 * should make: two numbers derived from a file.
 *
 * It is also the missing piece for Windows signing. Signing a .exe as a post
 * build step changes its bytes, so the Path A flow in docs/WINDOWS-SIGNING.md is
 * only safe if the feed is re-hashed afterward — see that doc.
 *
 *   node scripts/repatch-update-feed.mjs <feed.yml> [--dir <artifact dir>]
 *
 * The feed is edited in place. Only entries whose file is present on disk are
 * touched, so running it against a partial download set is safe.
 *
 * REFUSES TO SILENTLY DO NOTHING: if no entry in the feed matched a file on
 * disk, that is a wrong --dir or a renamed artifact, not a no-op, and it exits
 * non-zero. A re-hash step that quietly hashes nothing would leave the stale
 * feed in place while reporting success — the failure this script exists to stop.
 */
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

/** electron-updater stores sha512 as base64 of the raw digest, not hex. */
export function sha512Base64(buf) {
  return createHash('sha512').update(buf).digest('base64');
}

/**
 * Rewrite the sha512/size of every `files:` entry whose url is in `hashes`,
 * plus the top-level sha512 when it belongs to the file named by `path:`.
 *
 * Line-targeted on purpose: the feed is machine-generated by electron-builder
 * and round-tripping it through a YAML library would reformat lines this script
 * has no business touching (quoting of releaseDate, key order, indentation).
 *
 * @param {string} text  the feed file contents
 * @param {Record<string, {sha512: string, size: number}>} hashes  keyed by artifact filename
 * @returns {{text: string, changed: string[], skipped: string[]}}
 */
export function repatch(text, hashes) {
  const lines = text.split('\n');
  const changed = [];
  const seen = [];
  let current = null;      // filename of the `- url:` block being walked
  let topLevelPath = null;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];

    const urlM = /^(\s*-\s*url:\s*)(\S.*?)\s*$/.exec(line);
    if (urlM) {
      current = urlM[2];
      seen.push(current);
      continue;
    }

    // A top-level key (no leading space) ends the files: list.
    const topM = /^([A-Za-z0-9_]+):\s*(.*)$/.exec(line);
    if (topM) {
      if (topM[1] === 'path') topLevelPath = topM[2].trim().replace(/^['"]|['"]$/g, '');
      if (topM[1] === 'sha512' && topLevelPath && hashes[topLevelPath]) {
        lines[i] = `sha512: ${hashes[topLevelPath].sha512}`;
        if (!changed.includes(`${topLevelPath} (top-level)`)) changed.push(`${topLevelPath} (top-level)`);
      }
      // `files:` itself is a top-level key; don't let it clear the block cursor.
      if (topM[1] !== 'files') current = null;
      continue;
    }

    if (!current || !hashes[current]) continue;

    const shaM = /^(\s*)sha512:\s*/.exec(line);
    if (shaM) {
      lines[i] = `${shaM[1]}sha512: ${hashes[current].sha512}`;
      if (!changed.includes(current)) changed.push(current);
      continue;
    }
    const sizeM = /^(\s*)size:\s*/.exec(line);
    if (sizeM) {
      lines[i] = `${sizeM[1]}size: ${hashes[current].size}`;
      if (!changed.includes(current)) changed.push(current);
    }
  }

  return { text: lines.join('\n'), changed, skipped: seen.filter((f) => !hashes[f]) };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const feed = args.find((a) => !a.startsWith('--'));
  const dirFlag = args.indexOf('--dir');
  const dir = dirFlag >= 0 ? args[dirFlag + 1] : (feed ? path.dirname(feed) : '.');

  if (!feed) {
    process.stderr.write('usage: node scripts/repatch-update-feed.mjs <feed.yml> [--dir <artifact dir>]\n');
    process.exit(2);
  }
  if (!fs.existsSync(feed)) {
    process.stderr.write(`feed not found: ${feed}\n`);
    process.exit(2);
  }

  const text = fs.readFileSync(feed, 'utf8');
  // Hash every artifact the feed mentions that actually exists next to it.
  const named = [...text.matchAll(/^\s*-\s*url:\s*(\S.*?)\s*$/gm)].map((m) => m[1]);
  const hashes = {};
  for (const name of new Set(named)) {
    const p = path.join(dir, name);
    if (!fs.existsSync(p)) continue;
    const buf = fs.readFileSync(p);
    hashes[name] = { sha512: sha512Base64(buf), size: buf.length };
  }

  const r = repatch(text, hashes);
  if (!r.changed.length) {
    process.stderr.write(
      `\nre-hash failed — the feed names ${named.length} artifact(s) but none were found in "${dir}":\n` +
      named.map((n) => `  ${n}\n`).join('') +
      `\nWrong --dir, or the artifacts were renamed. Refusing to report success on a feed\n` +
      `that still describes the pre-signing bytes.\n`
    );
    process.exit(1);
  }

  fs.writeFileSync(feed, r.text);
  process.stdout.write(`re-hashed ${path.basename(feed)} — updated: ${r.changed.join(', ')}\n`);
  if (r.skipped.length) process.stdout.write(`  (left alone, not on disk: ${r.skipped.join(', ')})\n`);
}
